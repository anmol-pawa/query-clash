import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { QUESTIONS } from "@/content/interview";
import { JSON_FINE } from "@/content/interview/jsonFine";
import { RECURSIVE_FINE } from "@/content/interview/recursiveFine";
import { ALL_MISSIONS } from "@/content/chapters";
import { CODEX } from "@/content/codex";

const doc = readFileSync("docs/COVERAGE.md", "utf8");
const rows = doc.split("\n").filter((l) => l.startsWith("| ") && !l.startsWith("| ---") && !l.startsWith("| Topic"));

const questionIds = new Set(QUESTIONS.map((q) => q.id));
const missionIds = new Set(ALL_MISSIONS.map((m) => m.id));
const codexIds = new Set(CODEX.map((c) => c.id));

describe("coverage matrix", () => {
  it("names only things that exist", () => {
    const ticks = [...rows.join("\n").matchAll(/`([^`]+)`/g)].map((m) => m[1]);
    expect(ticks.length).toBeGreaterThan(100);
    for (const t of ticks) expect(missionIds.has(t) || codexIds.has(t) || questionIds.has(t), t).toBe(true);
  });

  it("gives every topic at least two example questions", () => {
    expect(rows.length).toBeGreaterThanOrEqual(25);
    for (const row of rows) {
      const cells = row.split("|").map((c) => c.trim());
      const ids = [...(cells[4] ?? "").matchAll(/`([^`]+)`/g)].map((m) => m[1]);
      expect(ids.length, cells[1]).toBeGreaterThanOrEqual(2);
      for (const id of ids) expect(questionIds.has(id), id).toBe(true);
    }
  });

  it("puts the mission column in missions and the codex column in codex", () => {
    for (const row of rows) {
      const cells = row.split("|").map((c) => c.trim());
      for (const m of cells[2].matchAll(/`([^`]+)`/g)) expect(missionIds.has(m[1]), m[1]).toBe(true);
      for (const m of cells[3].matchAll(/`([^`]+)`/g)) expect(codexIds.has(m[1]), m[1]).toBe(true);
    }
  });
});

describe("recursive CTE questions", () => {
  it("are in the interview pool", () => {
    expect(RECURSIVE_FINE).toHaveLength(9);
    for (const q of RECURSIVE_FINE) expect(questionIds.has(q.id), q.id).toBe(true);
  });

  it("have the traced numeric answers", () => {
    const num = (id: string) => RECURSIVE_FINE.find((q) => q.id === id)!;
    // Tree A -> (B, C), B -> (D, E), C -> F: the anchor plus five descendants.
    expect(num("recfine-row-count")).toMatchObject({ kind: "numeric", answer: 1 + 2 + 3 });
    // 1..5 generated by the recursion.
    expect(num("recfine-series-sum")).toMatchObject({ kind: "numeric", answer: [1, 2, 3, 4, 5].reduce((a, b) => a + b) });
  });
});

describe("JSON questions", () => {
  it("are in the interview pool with distinct keyed answers", () => {
    expect(JSON_FINE).toHaveLength(3);
    for (const q of JSON_FINE) {
      expect(questionIds.has(q.id), q.id).toBe(true);
      expect(q.kind, q.id).toBe("mcq");
    }
  });
});
